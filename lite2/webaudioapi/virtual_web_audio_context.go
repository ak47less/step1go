package webaudioapi

// Seconds is a time on the Web Audio timeline, measured in seconds.
type Seconds float64

// SampleRate is a number of PCM frames per second.
type SampleRate float64

// SampleCount is a number of PCM frames.
type SampleCount uint64

// SampleValue is one normalized PCM sample. The supported range is [-1, 1].
type SampleValue float32

// AudioContextState mirrors the state enum from the Web Audio API.
type AudioContextState string

const (
	AudioContextStateSuspended AudioContextState = "suspended"
	AudioContextStateRunning   AudioContextState = "running"
	AudioContextStateClosed    AudioContextState = "closed"
)

// OscillatorType identifies the waveform generated by an OscillatorNode.
type OscillatorType string

const (
	OscillatorTypeSine     OscillatorType = "sine"
	OscillatorTypeSquare   OscillatorType = "square"
	OscillatorTypeSawtooth OscillatorType = "sawtooth"
	OscillatorTypeTriangle OscillatorType = "triangle"
	OscillatorTypeCustom   OscillatorType = "custom"
)

// AudioParam represents an audio-rate parameter which can be automated.
//
// The time arguments follow the Web Audio API model: scheduling starts at
// zero when the context is created and continues while its clock is running.
type AudioParam interface {
	GetValue() float64
	SetValue(value float64)

	SetValueAtTime(value float64, startTime Seconds)
	LinearRampToValueAtTime(value float64, endTime Seconds)
	ExponentialRampToValueAtTime(value float64, endTime Seconds)
	SetTargetAtTime(target float64, startTime Seconds, timeConstant Seconds)
	CancelScheduledValues(startTime Seconds)
}

// AudioNode is the common contract for every node in an audio graph.
type AudioNode interface {
	Connect(destination AudioNode)
	Disconnect()
}

// AudioScheduledSourceNode is a source node whose lifetime can be scheduled.
type AudioScheduledSourceNode interface {
	AudioNode

	Start(when Seconds)
	Stop(when Seconds)
	SetOnEnded(handler func())
}

// OscillatorNode is a periodic waveform source.
type OscillatorNode interface {
	AudioScheduledSourceNode

	GetFrequency() AudioParam
	GetDetune() AudioParam
	GetType() OscillatorType
	SetType(nodeType OscillatorType)
}

// GainNode applies an audio-rate gain to all of its inputs.
type GainNode interface {
	AudioNode

	GetGain() AudioParam
}

// AudioDestinationNode is the final output node of a BaseAudioContext.
type AudioDestinationNode interface {
	AudioNode

	GetMaxChannelCount() int
}

// AudioBuffer owns one planar channel buffer for each audio channel.
type AudioBuffer interface {
	GetSampleRate() SampleRate
	GetLength() SampleCount
	GetNumberOfChannels() int
	GetChannelData(channel int) []SampleValue
}

// AudioBufferSourceNode plays an AudioBuffer.
type AudioBufferSourceNode interface {
	AudioScheduledSourceNode

	GetBuffer() AudioBuffer
	SetBuffer(buffer AudioBuffer)
	GetPlaybackRate() AudioParam
	GetDetune() AudioParam
}

// BaseAudioContext contains the methods shared by AudioContext and
// OfflineAudioContext.
type BaseAudioContext interface {
	// CreateOscillator creates a periodic waveform source.
	CreateOscillator() OscillatorNode

	// CreateGain creates a node which applies an audio-rate gain.
	CreateGain() GainNode

	// CreateBuffer allocates a planar PCM buffer.
	CreateBuffer(numberOfChannels int, length SampleCount, sampleRate SampleRate) AudioBuffer

	// CreateBufferSource creates a source which plays an AudioBuffer.
	CreateBufferSource() AudioBufferSourceNode

	// GetCurrentTime returns the current Web Audio context time.
	GetCurrentTime() Seconds

	// GetSampleRate returns the sample rate used by the context.
	GetSampleRate() SampleRate

	// GetDestination returns the context's final output node.
	GetDestination() AudioDestinationNode

	// GetState returns the current context lifecycle state.
	GetState() AudioContextState
}

// AudioContext is a one-to-one virtual counterpart of the Web Audio API
// AudioContext object. In JavaScript ports, the native AudioContext can replace
// this object while keeping the same call sites.
type AudioContext interface {
	BaseAudioContext

	// Close releases the context and its audio resources.
	Close()

	// Resume starts or restarts audio processing.
	Resume()

	// Suspend pauses audio processing while retaining the current graph.
	Suspend()
}
