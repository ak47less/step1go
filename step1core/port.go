package step1core

////////////////////////////////////////////////////////////////////////////////

type PortType int

const (
	PortTypeAudio PortType = 1
	PortTypeMIDI  PortType = 2
)

////////////////////////////////////////////////////////////////////////////////

type PortName string

type PortID string

////////////////////////////////////////////////////////////////////////////////

type PortInfo struct {
	Index int

	Name PortName

	ID PortID

	Type PortType

	Input Input

	Output Output

	Owner Element
}

////////////////////////////////////////////////////////////////////////////////

type Port interface {
	GetInfo(info *PortInfo) *PortInfo

	GetOwnerElement() Element

	Wire(w *Wire) error
}

type Reader interface {
	Read(lc *Bus) error
}

type Writer interface {
	Write(lc *Bus) error
}

type Input interface {
	Port
	Writer
}

type Output interface {
	Port
	Reader
}

