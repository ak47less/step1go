package step1core

////////////////////////////////////////////////////////////////////////////////

type PortType int

const (
	PortTypeAudio PortType = 1
	PortTypeMIDI  PortType = 2
)

////////////////////////////////////////////////////////////////////////////////

type PortName string

type PortID string

////////////////////////////////////////////////////////////////////////////////

type PortInfo struct {
	Index int

	Name PortName

	ID PortID

	Type PortType

	Input Input

	Output Output

	Owner Device
}

////////////////////////////////////////////////////////////////////////////////

type Port interface {
	GetInfo(info *PortInfo) *PortInfo

	GetOwnerDevice() Device

	Wire(w *Wire) error
}

type Reader interface {
	Read(bus *Bus) error
}

type Writer interface {
	Write(bus *Bus) error
}

type Input interface {
	Port
	Writer

	GetSource() Output
}

type Output interface {
	Port
	Reader
}

